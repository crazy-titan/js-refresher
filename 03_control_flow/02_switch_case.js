// Switch-Case is used when you have a lot of if else conditions. So, remove the if-else and just go with switch-case

const key= 3;

switch (key) {
    case 1:
        console.log("January");
        break;
    case 2:
        console.log("Feb");
        break;
    case 3:
        console.log("Yes! its March");
        break;
    default:
        console.log("its a Default value if nothing matches")
        break;
}

// break is used to avoid the waterFall model of the programming language!
